const tables: Record<InterfaceLanguage, TranslationTable> = { uk, en, ru };

export function uiText(language: InterfaceLanguage, key: UiStringKey, params?: Params): string {
  let text = tables[language][key] ?? en[key];
  if (!params) return text;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function createUiTranslator(language: InterfaceLanguage) {
  return (key: UiStringKey, params?: Params) => uiText(language, key, params);
}

export function getLocalizedModelDownloadStage(
  language: InterfaceLanguage,
  stage: string,
  fallback: string
): string {
  const key = `models.stage.${stage}` as UiStringKey;
  return key in tables[language] ? tables[language][key] : fallback;
}

export function getLocalizedVoiceDescription(language: InterfaceLanguage, voiceId: string, fallback: string): string {
  const key = `voice.${voiceId}` as UiStringKey;
  return key in tables[language] ? tables[language][key] : fallback;
}

